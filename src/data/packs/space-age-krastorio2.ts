/**
 * Merges base items/recipes/machines/technologies with mod overrides by unique `id`.
 * Whenever the mod defines an entity or recipe with the same `id`, the modded entry
 * strictly replaces the base/vanilla entry cleanly without duplicate IDs.
 */
function mergeModOverrides<T extends { id: string }>(base: T[], overrides: T[]): T[] {
  const merged = new Map<string, T>();
  for (const entry of base) {
    merged.set(entry.id, entry);
  }
  for (const override of overrides) {
    merged.set(override.id, override);
  }
  return Array.from(merged.values());
}

function extendBaseMachineCategories(id: string, extraCategories: string[]): MachineDef {
  const base = SPACE_AGE_2_0_PACK.machines.find((m) => m.id === id);
  if (!base) {
    throw new Error(`Base machine "${id}" not found in SPACE_AGE_2_0_PACK.`);
  }
  const merged = Array.from(new Set([...base.craftingCategories, ...extraCategories]));
  return { ...base, craftingCategories: merged };
}

