import { describe, expect, it } from 'vitest';
import { DEFAULT_PACK_ID, packRegistry } from '../../data/packRegistry.ts';
import { solveProductionPlan } from '../../engine/solver.ts';
import { decodeBlueprintString, encodeBlueprintString } from '../blueprintCodec.ts';
import { synthesizeFactoryLayout } from '../layoutSynthesizer.ts';

describe('Fase 4 — Spatial 2D Assembly Line Synthesizer & Blueprint Codec', () => {
  const index = packRegistry.getIndex(DEFAULT_PACK_ID);

  it('synthesizes a collision-free 2D grid with machines, twin-lane belts, splitters, and inserters', () => {
    const config = {
      packId: DEFAULT_PACK_ID,
      targets: [{ itemId: 'electronic-circuit', ratePerSec: 15 }],
      defaultBeltId: 'express-transport-belt',
    };
    const solveResult = solveProductionPlan(index, config);
    const layout = synthesizeFactoryLayout(index, solveResult, config, 'compact');

    // Total installed machines = 24 + 36 + 15 + 10 = 85
    expect(layout.stats.machineCount).toBe(85);
    expect(layout.stats.beltCount).toBeGreaterThan(50);
    expect(layout.stats.inserterCount).toBeGreaterThanOrEqual(85 * 2);
    expect(layout.stats.splitterCount).toBeGreaterThan(0);

    // Verify ZERO tile collisions across all entities
    const occupied = new Set<string>();
    for (const e of layout.entities) {
      for (let dx = 0; dx < e.width; dx++) {
        for (let dy = 0; dy < e.height; dy++) {
          const key = `${e.tileX + dx},${e.tileY + dy}`;
          expect(occupied.has(key)).toBe(false);
          occupied.add(key);
        }
      }
    }
  });

  it('generates pipe manifolds and long-handed inserters for multi-ingredient + fluid recipes', () => {
    const config = {
      packId: DEFAULT_PACK_ID,
      targets: [{ itemId: 'processing-unit', ratePerSec: 0.5 }],
      defaultBeltId: 'express-transport-belt',
    };
    const solveResult = solveProductionPlan(index, config);
    const layout = synthesizeFactoryLayout(index, solveResult, config, 'compact');

    expect(layout.stats.pipeCount).toBeGreaterThan(0);
    expect(layout.entities.some((e) => e.name === 'long-handed-inserter')).toBe(true);
    expect(layout.entities.some((e) => e.recipeId === 'processing-unit')).toBe(true);
  });

  it('encodes and decodes valid Factorio 0eN... blueprint strings preserving recipes and modules', () => {
    const config = {
      packId: DEFAULT_PACK_ID,
      targets: [{ itemId: 'electronic-circuit', ratePerSec: 7.5 }],
      rawResourceOverrides: ['iron-plate', 'copper-plate'],
      stageOverrides: {
        'electronic-circuit': {
          moduleIds: ['productivity-module-2', 'productivity-module-2'],
        },
      },
    };
    const solveResult = solveProductionPlan(index, config);
    const layout = synthesizeFactoryLayout(index, solveResult, config, 'compact');

    const bpString = encodeBlueprintString(
      layout.entities,
      'Green Circuits 7.5/s',
      'Generated by Factorio Production Planner'
    );
    expect(bpString.startsWith('0eN')).toBe(true);

    const decoded = decodeBlueprintString(bpString);
    expect(decoded.blueprint.label).toBe('Green Circuits 7.5/s');
    expect(decoded.blueprint.entities.length).toBe(layout.entities.length);

    const ecMachine = decoded.blueprint.entities.find((e) => e.recipe === 'electronic-circuit');
    expect(ecMachine).toBeDefined();
    expect(Array.isArray(ecMachine?.items)).toBe(true);
    if (Array.isArray(ecMachine?.items)) {
      const modId = ecMachine.items[0]?.id;
      expect(typeof modId === 'string' ? modId : modId?.name).toBe('productivity-module-2');
      expect(ecMachine.items[0]?.items?.in_inventory?.length).toBe(2);
    }
  });

  it('Fase 5 — places physical beacons & electric poles without collisions and supports direct insertion', () => {
    const config = {
      packId: DEFAULT_PACK_ID,
      targets: [{ itemId: 'automation-science-pack', ratePerSec: 1 }],
      rawResourceOverrides: ['iron-plate', 'copper-plate'],
      defaultBeltId: 'express-transport-belt',
      stageOverrides: {
        'automation-science-pack': {
          beacon: {
            beaconId: 'beacon',
            count: 2,
            moduleIds: ['speed-module-3', 'speed-module-3'],
          },
        },
      },
    };

    const solveResult = solveProductionPlan(index, config);
    const layout = synthesizeFactoryLayout(index, solveResult, config, {
      compactionMode: 'compact',
      includeBeacons: true,
      includePowerPoles: true,
      directInsertion: true,
    });

    expect(layout.stats.beaconCount).toBeGreaterThanOrEqual(2);
    expect(layout.stats.poleCount).toBeGreaterThan(0);

    // Direct insertion couples iron-gear-wheel directly into automation-science-pack
    expect(
      layout.zones.some(
        (z) => z.label.includes('Iron Gear Wheel') && z.label.includes('Automation Science Pack')
      )
    ).toBe(true);

    // Zero tile collisions across machines, beacons, poles, inserters, and belts
    const occupied = new Set<string>();
    for (const e of layout.entities) {
      for (let dx = 0; dx < e.width; dx++) {
        for (let dy = 0; dy < e.height; dy++) {
          const key = `${e.tileX + dx},${e.tileY + dy}`;
          expect(occupied.has(key)).toBe(false);
          occupied.add(key);
        }
      }
    }
  });

  it('Fase 5 — imports Factorio 0eN... blueprint strings (including Space Age / K2 entities) back into editable GridEntity[]', async () => {
    const { parseBlueprintToEntities } = await import('../blueprintCodec.ts');
    const k2Index = packRegistry.getIndex('factorio-space-age-krastorio2');
    const config = {
      packId: 'factorio-space-age-krastorio2',
      targets: [{ itemId: 'electromagnetic-science-pack', ratePerSec: 1 }],
      defaultBeltId: 'turbo-transport-belt',
    };
    const solveResult = solveProductionPlan(k2Index, config);
    const layout = synthesizeFactoryLayout(k2Index, solveResult, config, {
      compactionMode: 'compact',
      includeBeacons: true,
      includePowerPoles: true,
    });

    const bpString = encodeBlueprintString(layout.entities, 'EM Science');
    const imported = parseBlueprintToEntities(bpString, k2Index);

    expect(imported.label).toBe('EM Science');
    expect(imported.entities.length).toBe(layout.entities.length);
    expect(imported.entities.some((e) => e.name === 'electromagnetic-plant')).toBe(true);
    expect(imported.entities.some((e) => e.kind === 'electric-pole')).toBe(true);
  });
});
